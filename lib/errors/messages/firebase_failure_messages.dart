/// Message for a Firebase SDK failure, or null when [failure] isn't one.
///
/// Codes not in [_keysByCode] fall back to `unknown_error`.
String? firebaseFailureMessage(Failure failure) => switch (failure) {
  FirebaseFailure(:final firebaseErrorCode?) =>
    (_keysByCode[firebaseErrorCode] ?? 'unknown_error').tr(),
  FirebaseFailure() => 'service_unavailable_error'.tr(),
  _ => null,
};

